import { contactRecipients } from "./config";
import { sendMail, type MailAttachment } from "./send";
import {
  formatJerusalem,
  inquirySubject,
  oneLine,
  renderStaffEmail,
  replyAddress,
  resetEmailHtml,
  safePageUrl,
} from "./template";

export type Inquiry = {
  name: string;
  email?: string;
  phone?: string;
  customerType: string;
  message: string;
  pageUrl?: string;
  at?: Date;
  attachments?: MailAttachment[];
};

/** Emails the office every customer submission. Throws MailError when delivery fails. */
export async function notifyInquiry(input: Inquiry): Promise<void> {
  const at = input.at ?? new Date();
  const email = input.email?.trim() ?? "";
  const page = safePageUrl(input.pageUrl);
  const rendered = renderStaffEmail({
    intro: "התקבלה פנייה חדשה מהאתר.",
    rows: [
      { label: "שם", value: input.name },
      { label: "אימייל", value: email || "לא נמסר" },
      { label: "טלפון", value: input.phone?.trim() || "לא נמסר" },
      { label: "סוג לקוח", value: input.customerType },
      { label: "הודעה", value: input.message },
      page ? { label: "עמוד", value: page, href: page } : { label: "עמוד", value: "לא נמסר" },
      { label: "זמן", value: formatJerusalem(at) },
    ],
  });
  await sendMail({
    to: contactRecipients(),
    subject: inquirySubject(input.name, input.customerType),
    html: rendered.html,
    text: rendered.text,
    replyTo: replyAddress(email),
    attachments: input.attachments,
  });
}

export async function notifyDocumentUpload(input: {
  name: string;
  email: string;
  customerType: string;
  fileName: string;
  fileCount: number;
  adminUrl: string;
}): Promise<void> {
  const page = safePageUrl(input.adminUrl);
  const customerType = input.customerType.trim() || "לא צוין";
  const rendered = renderStaffEmail({
    intro: "לקוח העלה מסמך לאתר.",
    rows: [
      { label: "שם", value: input.name.trim() || "לא נמסר" },
      { label: "אימייל", value: input.email.trim() || "לא נמסר" },
      { label: "סוג לקוח", value: customerType },
      { label: "קובץ", value: input.fileName },
      { label: "מספר קבצים", value: String(input.fileCount) },
      page
        ? { label: "ניהול לקוחות", value: "לכרטיס הלקוח", href: page }
        : { label: "ניהול לקוחות", value: "לא נמסר" },
      { label: "זמן", value: formatJerusalem(new Date()) },
    ],
  });
  await sendMail({
    to: contactRecipients(),
    subject: `העלאת מסמכים מהאתר – ${oneLine(input.name || "לקוח")} (${oneLine(customerType, 40)})`,
    html: rendered.html,
    text: rendered.text,
    replyTo: replyAddress(input.email),
  });
}

/** Customer-facing password reset. The link is generated by us; Resend only delivers it. */
export async function sendPasswordResetEmail(to: string, name: string, link: string): Promise<void> {
  await sendMail({
    to: [to],
    subject: "איפוס סיסמה | שילן שירותי המרה",
    html: resetEmailHtml(name, link),
    text: `שלום ${name},\n\nלאיפוס הסיסמה באתר שילן היכנסו לקישור:\n${link}\n\nהקישור תקף לשעה אחת. אם לא ביקשתם לאפס את הסיסמה, אפשר להתעלם מהודעה זו.`,
  });
}
